"""Rebuild TVM/DOCUMENT-INDEX.md from the documents on disk.

Usage (from TVM/):  python scripts/build_index.py
Reads the front matter (id, date, title, status) of every dated record and lists the
standing documents of each folder. Writes only when the content changes.
"""
import glob
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "lib"))
import tvmlib  # noqa: E402

SECTIONS = [
    ("01-Instructions", None, "Permanent rules for all TVM work"),
    ("02-Knowledge-Base", None, "Verified overview of the TVM org and project"),
    ("03-Requirements", "REQ", "One dated record per requirement, task, enhancement or defect"),
    ("04-Change-Records", "CR", "One dated record per actual business-record or configuration-data change"),
    ("05-Conflicts", "CF", "One dated record per error, conflict or unexpected behaviour"),
    ("06-Deployment", "DEP", "Procedures, checklists and one dated record per release or validation"),
    ("07-Technical-Documents", None, "Technical documents, generated inventories and component change history"),
    ("08-QA", None, "Automated test reports (ATR) and manual test cases (MTC), see 01-Instructions/QA-Process.md"),
]
FM_RX = re.compile(r"^---\s*\n(.*?)\n---\s*\n", re.S)


def front_matter(path):
    with open(path, encoding="utf-8") as fh:
        text = fh.read(4000)
    meta = {}
    m = FM_RX.match(text)
    if m:
        for line in m.group(1).splitlines():
            if ":" in line:
                k, v = line.split(":", 1)
                meta[k.strip()] = v.strip().strip('"')
    if "title" not in meta:
        h = re.search(r"^#\s+(.+)$", text, re.M)
        meta["title"] = h.group(1).strip() if h else os.path.basename(path)
    return meta


def build():
    out = ["# TVM Document Index", "",
           "Generated by `scripts/build_index.py`. Do not edit by hand; it is rebuilt on every automatic commit.", "",
           "Dated records are named `YYYY-MM-DD-<TYPE>-<NNN>-<slug>.md` and created with "
           "`python scripts/new_doc.py <TYPE> \"<title>\"`. IDs are never reused.", ""]
    summary = ["| Folder | Record type | Purpose | Records | Next free ID |", "|---|---|---|---|---|"]
    body = []
    for folder, prefix, purpose in SECTIONS:
        fdir = os.path.join(tvmlib.TVM_DIR, folder)
        pattern = os.path.join(fdir, "**", "*.md") if folder == "08-QA" else os.path.join(fdir, "*.md")
        files = sorted(glob.glob(pattern, recursive=True))
        dated = [f for f in files if prefix and re.match(rf"^\d{{4}}-\d{{2}}-\d{{2}}-{prefix}-\d+", os.path.basename(f))]
        standing = [f for f in files if f not in dated and os.path.basename(f).lower() != "readme.md"]
        nums = [int(re.search(rf"-{prefix}-(\d+)", os.path.basename(f)).group(1)) for f in dated] if prefix else []
        nxt = f"{prefix}-{(max(nums) + 1 if nums else 1):03d}" if prefix else "n/a"
        summary.append(f"| [{folder}]({folder}/) | {prefix or 'standing docs'} | {purpose} | {len(dated)} | {nxt} |")
        body += ["", f"## {folder}", ""]
        if standing:
            body += ["| Document | Title |", "|---|---|"]
            for f in standing:
                rel = os.path.relpath(f, tvmlib.TVM_DIR).replace("\\", "/")
                body.append(f"| [{os.path.basename(f)}]({rel}) | {front_matter(f)['title']} |")
        if folder == "07-Technical-Documents":
            subs = sorted(d for d in os.listdir(fdir) if os.path.isdir(os.path.join(fdir, d)))
            if subs:
                body += ["", "Subfolders: " + " · ".join(f"[{d}](07-Technical-Documents/{d}/)" for d in subs)]
        if prefix:
            body += ["", "| ID | Date | Title | Status |", "|---|---|---|---|"] if dated else ["", "_No records yet._"]
            for f in sorted(dated, key=lambda p: os.path.basename(p)):
                meta = front_matter(f)
                rel = os.path.relpath(f, tvmlib.TVM_DIR).replace("\\", "/")
                body.append(f"| [{meta.get('id', '?')}]({rel}) | {meta.get('date', '?')} | {meta['title']} | "
                            f"{meta.get('status', '?')} |")
    content = "\n".join(out + summary + body) + "\n"
    return tvmlib.write_if_changed(os.path.join(tvmlib.TVM_DIR, "DOCUMENT-INDEX.md"), content)


if __name__ == "__main__":
    print("DOCUMENT-INDEX.md " + ("updated" if build() else "unchanged"))
