"""Generate the Epicare metadata inventories in 07-Technical-Documents/Metadata-Inventory/ from force-app.

Usage (from Epicare/):  python scripts/build_inventory.py
Offline: reads only local source. Output is deterministic (no timestamps), so running it
twice with unchanged source changes nothing. Dates live in 07-Technical-Documents/Change-History.md.
"""
import glob
import os
import re
import sys
import xml.etree.ElementTree as ET

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "lib"))
import projlib  # noqa: E402

SRC = os.path.join(projlib.PROJECT_DIR, "force-app", "main", "default")
OUT = os.path.join(projlib.PROJECT_DIR, "07-Technical-Documents", "Metadata-Inventory")
NS = "{http://soap.sforce.com/2006/04/metadata}"
HEADER = ("_Generated by `scripts/build_inventory.py` from `force-app/main/default`. Do not edit by hand: "
          "it is regenerated on every automatic commit. Hand-written explanations belong in the topic folders "
          "of `07-Technical-Documents/`._\n")
LINK_BASE = "../../force-app/main/default"
written = []


def emit(name, title, lines):
    path = os.path.join(OUT, name)
    content = f"# {title}\n\n{HEADER}\n" + "\n".join(lines).rstrip() + "\n"
    if projlib.write_if_changed(path, content):
        written.append(os.path.relpath(path, projlib.PROJECT_DIR))


def cell(text, limit=120):
    text = re.sub(r"\s+", " ", (text or "")).strip().replace("|", "\\|")
    return text if len(text) <= limit else text[: limit - 1] + "…"


def xml(path):
    try:
        return ET.parse(path).getroot()
    except ET.ParseError:
        return None


def t(node, tag, default=""):
    if node is None:
        return default
    el = node.find(NS + tag)
    return el.text if el is not None and el.text is not None else default


def files(pattern):
    return sorted(glob.glob(os.path.join(SRC, pattern)))


def base(path, suffix):
    return os.path.basename(path)[: -len(suffix)]


# ------------------------------------------------------------------ Apex

def strip_comments(code):
    code = re.sub(r"/\*.*?\*/", "", code, flags=re.S)
    return re.sub(r"//[^\n]*", "", code)


def apex_classes():
    paths = files("classes/*.cls")
    src = {}
    for p in paths:
        with open(p, encoding="utf-8", errors="replace") as fh:
            src[base(p, ".cls")] = fh.read()
    names = set(src)
    tests = {n for n, c in src.items() if re.search(r"@is[Tt]est", c)}
    rows, test_rows = [], []
    for name in sorted(src):
        raw = src[name]
        code = strip_comments(raw)
        lines = raw.count("\n") + 1
        if name in tests:
            covered = sorted(n for n in names - tests if re.search(rf"\b{re.escape(n)}\b", code))
            test_rows.append(f"| `{name}` | {cell(', '.join(covered), 160)} | {lines} |")
            continue
        kinds = []
        for rx, label in [(r"Database\.Batchable", "Batch"), (r"\bSchedulable\b", "Schedulable"),
                          (r"\bQueueable\b", "Queueable"), (r"@RestResource", "REST resource"),
                          (r"@InvocableMethod", "Invocable"), (r"@AuraEnabled", "LWC/Aura controller"),
                          (r"\bwebservice\b", "SOAP web service"), (r"implements\s+Messaging\.InboundEmailHandler", "Email handler"),
                          (r"\binterface\b\s+" + re.escape(name), "Interface")]:
            if re.search(rx, code, re.I if label == "SOAP web service" else 0):
                kinds.append(label)
        if not kinds and re.search(r"Handler|Helper|Trigger", name):
            kinds.append("Trigger handler/helper")
        sharing = re.search(r"\b(with|without|inherited)\s+sharing\b", code)
        objs = sorted(set(re.findall(r"\bFROM\s+([A-Za-z0-9_]+)", code, re.I)) - {"WHERE"})
        dml = bool(re.search(r"\b(insert|update|upsert|delete|undelete|merge)\s+[A-Za-z_(\[]|Database\.(insert|update|upsert|delete)", code))
        callout = "Yes" if re.search(r"HttpRequest|callout:", code) else ""
        named = sorted(set(re.findall(r"callout:([A-Za-z0-9_]+)", code)))
        cov = sorted(n for n in tests if re.search(rf"\b{re.escape(name)}\b", strip_comments(src[n])))
        rows.append(f"| [`{name}`]({LINK_BASE}/classes/{name}.cls) | {', '.join(kinds) or 'Class'} | "
                    f"{sharing.group(1) + ' sharing' if sharing else 'not declared'} | {cell(', '.join(objs), 90)} | "
                    f"{'Yes' if dml else ''} | {callout}{' (' + ', '.join(named) + ')' if named else ''} | "
                    f"{cell(', '.join(cov), 80) or '**none found**'} | {lines} |")
    emit("Apex-Classes.md", "Apex Classes — inventory", [
        f"**{len(rows)} classes** and **{len(test_rows)} test classes** (unmanaged).",
        "Columns are read from the code by pattern matching: verify before relying on them. "
        "*Tests referencing* lists test classes whose code mentions the class name.", "",
        "| Class | Kind | Sharing | Objects queried (SOQL FROM) | DML | Callouts | Tests referencing | Lines |",
        "|---|---|---|---|---|---|---|---|", *rows, "", "## Test classes", "",
        "| Test class | Classes referenced | Lines |", "|---|---|---|", *test_rows])
    return len(rows), len(test_rows), names


def apex_triggers(class_names):
    rows = []
    for p in files("triggers/*.trigger"):
        name = base(p, ".trigger")
        with open(p, encoding="utf-8", errors="replace") as fh:
            code = fh.read()
        m = re.search(r"trigger\s+\w+\s+on\s+(\w+)\s*\(([^)]*)\)", code, re.I)
        obj, events = (m.group(1), cell(m.group(2))) if m else ("?", "?")
        meta = xml(p + "-meta.xml")
        status = t(meta, "status", "?")
        refs = sorted(n for n in class_names if re.search(rf"\b{re.escape(n)}\b", strip_comments(code)))
        rows.append(f"| [`{name}`]({LINK_BASE}/triggers/{name}.trigger) | {obj} | {events} | {status} | "
                    f"{cell(', '.join(refs), 120)} | {code.count(chr(10)) + 1} |")
    emit("Apex-Triggers.md", "Apex Triggers — inventory", [
        f"**{len(rows)} triggers** (unmanaged).", "",
        "| Trigger | Object | Events | Status | Classes referenced | Lines |", "|---|---|---|---|---|---|", *rows])
    return len(rows)


