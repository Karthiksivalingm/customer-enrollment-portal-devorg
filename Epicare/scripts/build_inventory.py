def objects():
    obj_rows, vr_rows, field_total = [], [], 0
    for odir in sorted(glob.glob(os.path.join(SRC, "objects", "*"))):
        if not os.path.isdir(odir):
            continue
        name = os.path.basename(odir)
        r = xml(os.path.join(odir, f"{name}.object-meta.xml"))
        fields = sorted(glob.glob(os.path.join(odir, "fields", "*.field-meta.xml")))
        vrs = sorted(glob.glob(os.path.join(odir, "validationRules", "*.validationRule-meta.xml")))
        rts = glob.glob(os.path.join(odir, "recordTypes", "*.recordType-meta.xml"))
        field_total += len(fields)
        frows, rels = [], set()
        for fp in fields:
            f = xml(fp)
            fname = base(fp, ".field-meta.xml")
            ftype = t(f, "type")
            ref = ", ".join(e.text for e in (f.findall(NS + "referenceTo") if f is not None else []) if e.text)
            if ref:
                rels.add(f"{fname} → {ref}")
            flags = [x for x, tag in [("required", "required"), ("unique", "unique"), ("external ID", "externalId")]
                     if t(f, tag) == "true"]
            if t(f, "formula"):
                flags.append("formula")
            frows.append(f"| `{fname}` | {cell(t(f, 'label'), 50)} | {ftype}{' (' + ref + ')' if ref else ''} | "
                         f"{', '.join(flags)} | {cell(t(f, 'description') or t(f, 'inlineHelpText'), 90)} |")
        for vp in vrs:
            v = xml(vp)
            vr_rows.append(f"| `{name}` | [`{base(vp, '.validationRule-meta.xml')}`]({LINK_BASE}/objects/{name}/validationRules/"
                           f"{os.path.basename(vp)}) | {t(v, 'active')} | {cell(t(v, 'errorMessage'), 100)} |")
        lines = [f"Source: [`objects/{name}`]({LINK_BASE.replace('../../', '../../../')}/objects/{name}/)", "",
                 f"| Property | Value |", "|---|---|",
                 f"| Label | {cell(t(r, 'label'))} |", f"| Sharing model | {t(r, 'sharingModel') or 'n/a (standard default)'} |",
                 f"| Unmanaged fields in source | {len(fields)} |", f"| Record types | {len(rts)} |",
                 f"| Validation rules | {len(vrs)} |", "",
                 "## Fields", "", "| API name | Label | Type | Flags | Description / help |", "|---|---|---|---|---|", *frows]
        path = os.path.join(OUT, "Objects", f"{name}.md")
        content = f"# {name}\n\n{HEADER}\n" + "\n".join(lines) + "\n"
        if projlib.write_if_changed(path, content):
            written.append(os.path.relpath(path, projlib.PROJECT_DIR))
        obj_rows.append(f"| [`{name}`](Objects/{name}.md) | {cell(t(r, 'label'), 50)} | {'Custom' if '__' in name else 'Standard'} | "
                        f"{t(r, 'sharingModel')} | {len(fields)} | {len(rts)} | {len(vrs)} | {cell('; '.join(sorted(rels)), 160)} |")
    emit("Objects-and-Fields.md", "Objects and Fields — inventory", [
        f"**{len(obj_rows)} objects**, **{field_total} unmanaged fields** in source. Standard objects are included "
        "only because they carry unmanaged custom fields. Managed-package fields are excluded by `.forceignore`.", "",
        "| Object | Label | Kind | Sharing | Fields | Record types | Validation rules | Relationships (lookup/master-detail) |",
        "|---|---|---|---|---|---|---|---|", *obj_rows])
    emit("Validation-Rules.md", "Validation Rules — inventory", [
        f"**{len(vr_rows)} validation rules**.", "", "| Object | Rule | Active | Error message |", "|---|---|---|---|", *vr_rows])
    return len(obj_rows), field_total, len(vr_rows)


