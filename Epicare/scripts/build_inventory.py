def simple(folder, suffix, cols, getter):
    rows = []
    for p in files(f"{folder}/*{suffix}"):
        r = xml(p)
        rows.append("| " + " | ".join([f"`{base(p, suffix)}`"] + [cell(x, 90) for x in getter(r)]) + " |")
    return rows


def components():
    lwc = []
    for d in sorted(glob.glob(os.path.join(SRC, "lwc", "*"))):
        if os.path.isdir(d):
            n = os.path.basename(d)
            m = xml(os.path.join(d, f"{n}.js-meta.xml"))
            targets = [e.text for e in m.findall(f".//{NS}target")] if m is not None else []
            apex = set()
            for js in glob.glob(os.path.join(d, "*.js")):
                with open(js, encoding="utf-8", errors="replace") as fh:
                    apex |= set(re.findall(r"@salesforce/apex/([A-Za-z0-9_]+)\.", fh.read()))
            lwc.append(f"| `{n}` | {t(m, 'isExposed')} | {cell(', '.join(targets), 90)} | {cell(', '.join(sorted(apex)), 80)} |")
    aura = []
    for d in sorted(glob.glob(os.path.join(SRC, "aura", "*"))):
        if os.path.isdir(d):
            n = os.path.basename(d)
            ctrl = ""
            for ext in (".cmp", ".app", ".evt", ".intf"):
                fp = os.path.join(d, n + ext)
                if os.path.exists(fp):
                    with open(fp, encoding="utf-8", errors="replace") as fh:
                        m = re.search(r'controller="([^"]+)"', fh.read())
                    ctrl = m.group(1) if m else ""
                    kind = ext[1:]
                    break
            else:
                kind = "?"
            aura.append(f"| `{n}` | {kind} | {ctrl} |")
    vf = []
