def flows():
    rows, by_status = [], {}
    for p in files("flows/*.flow-meta.xml"):
        name = base(p, ".flow-meta.xml")
        r = xml(p)
        if r is None:
            rows.append(f"| `{name}` | **unparseable XML** | | | | | | |")
            continue
        start = r.find(NS + "start")
        obj = t(start, "object")
        trig = t(start, "recordTriggerType") or t(start, "triggerType")
        when = t(start, "triggerType")
        status = t(r, "status", "?")
        by_status[status] = by_status.get(status, 0) + 1
        subs = sorted({t(s, "flowName") for s in r.findall(NS + "subflows")})
        counts = {k: len(r.findall(NS + k)) for k in ("decisions", "recordLookups", "recordCreates",
                                                     "recordUpdates", "recordDeletes", "actionCalls")}
        faults = len(r.findall(f".//{NS}faultConnector"))
        launch = r.find(NS + "processType")
        ptype = launch.text if launch is not None else "?"
        trigger_desc = " ".join(x for x in [when, trig, obj] if x) or ("Screen" if ptype == "Flow" else "")
        rows.append(f"| [`{name}`]({LINK_BASE}/flows/{name}.flow-meta.xml) | {cell(t(r, 'label'), 60)} | {ptype} | "
                    f"{cell(trigger_desc, 60)} | {status} | {counts['decisions']}/{counts['recordLookups']}/"
                    f"{counts['recordCreates'] + counts['recordUpdates'] + counts['recordDeletes']}/{counts['actionCalls']} | "
                    f"{faults} | {cell(', '.join(subs), 80)} |")
    emit("Flows.md", "Flows — inventory", [
        f"**{len(rows)} flows** (unmanaged). Status: " + ", ".join(f"{k} {v}" for k, v in sorted(by_status.items())) + ".",
        "Status is the version stored in source (retrieval returns the active version where one exists). "
        "Activation is never changed automatically.", "",
        "*Elements* = decisions / lookups / creates+updates+deletes / action calls. *Faults* = fault connectors.", "",
        "| Flow | Label | Type | Trigger (when / type / object) | Status | Elements | Faults | Subflows |",
        "|---|---|---|---|---|---|---|---|", *rows])
    return len(rows), by_status


